"""Renderer pilot (build step 3), at final print size:

* row 1: the Fig. 4a unfolded-CNS triptych in the glass-shell look (numba): signed cue difference (cells > 1 mV),
  maximum projection of |cue difference| (0.01-10 mV, log) and spiking cells; plus the signed tile with the
  ChimeraX shaded shell composited under the same cells;
* row 2: two compositions for the Fig. 1a anchor (dorsal oblique; lateral anterior-ventral oblique).

Run: .\\MIGRATION\\python\\python.exe -B -X utf8 MIGRATION\\launch.py --script manuscript\\figures\\render\\pilot.py
Outputs: manuscript/figures/renders/pilot/ (tiles + JSON sidecars, ChimeraX inputs and log, pilot_sheet.pdf/.png).
"""
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

FIG = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FIG))
from lib import figstyle as fs, palette as pal  # noqa: E402
from render import project as rp  # noqa: E402

RESULTS = rp.ROOT / "manuscript" / "results" / "figure_data"
OUT = FIG / "renders" / "pilot"
CHIMERAX = Path(r"D:\ChimeraX 1.11.1\bin\ChimeraX.exe")
TILE_W, TILE_H = 39.4, 60.0                      # Fig. 4a tiles (mm)
ANCHOR_W, ANCHOR_H = 119.4, 68.6                 # Fig. 1a anchor (mm)
SHELL = "#8E9BA8"
DV_MIN, DV_MAX = 1.0, 20.0                       # signed tile: cells with |dv| > 1 mV, colour saturates at 20 mV
ANCHOR_VIEWS = {
    "dorsal_oblique": ((0.45, -1.0, -0.25), (1.0, 0.0, 0.0)),
    "lateral_oblique": ((0.8, 0.35, -0.5), (0.0, 1.0, 0.0)),
}


def px(mm):
    return int(round(mm * fs.MM * fs.DPI))


def no_lamina(meta):
    """The lamina surfaces are truncated by the EM volume (flat cut faces); they are omitted from the shell."""
    return not meta["label"].startswith("LA(")


def load_cells():
    cells = pd.read_csv(RESULTS / "fd_cells.csv", low_memory=False)
    state = pd.read_csv(RESULTS / "fd_soma_state.csv", usecols=["cell", "dv_m0_mv", "spikes_m0"])
    return cells.merge(state, on="cell", validate="one_to_one")


def somata(cells):
    s = cells.dropna(subset=["soma_x_um"])
    return s, s[["soma_x_um", "soma_y_um", "soma_z_um"]].to_numpy()


def signed_colours(dv):
    """Colour (linear RGB) and opacity for cells with |dv| >= DV_MIN: log position between DV_MIN and DV_MAX."""
    u = np.clip(np.log10(np.abs(dv) / DV_MIN) / np.log10(DV_MAX / DV_MIN), 0, 1)
    t = 0.5 + np.sign(dv) * (0.26 + 0.24 * u)          # skip the dark centre: 1 mV is already a clear colour
    return rp.srgb_to_linear(pal.SIGNED_ON_DARK(t)[:, :3]), 0.75 + 0.25 * u


def unfolded_tile(xyz, shell=True):
    tile = rp.Tile(rp.fit_view(xyz, px(TILE_W), px(TILE_H), unfold=True, margin=0.03, ss=3))
    if shell:
        tile.shell(rp.load_regions(), colour=SHELL, strength=0.16, gamma=2.2, fill=0.015, select=no_lamina)
    return tile


def background(tile, xyz, alpha=0.35):
    tile.discs(xyz, 1.3, pal.TILE["somata"], alpha, order="add", label="all somata")


def signed_layer(tile, s, xyz):
    dv = s["dv_m0_mv"].to_numpy()
    keep = np.abs(dv) > DV_MIN
    rgb, alpha = signed_colours(dv[keep])
    tile.discs(xyz[keep], 2.0, rgb, alpha, order="value", values=np.abs(dv[keep]), label=f"|dv| > {DV_MIN} mV (M0)")
    return int(keep.sum())


def triptych(cells):
    s, xyz = somata(cells)
    out = {}
    t = unfolded_tile(xyz)
    background(t, xyz)
    n = signed_layer(t, s, xyz)
    out["signed"] = t.resolve()
    t.save(OUT / "fig4a_signed_glass.png", out["signed"], dict(cells_coloured=n))
    t = unfolded_tile(xyz)
    t.max_projection(xyz, 1.8, np.abs(s["dv_m0_mv"].to_numpy()), pal.MAGNITUDE_ON_DARK, 0.01, 10.0, log=True, label="|dv| MIP")
    out["magnitude"] = t.resolve()
    t.save(OUT / "fig4a_magnitude_glass.png", out["magnitude"])
    t = unfolded_tile(xyz)
    background(t, xyz, 0.45)
    sp = s["spikes_m0"].to_numpy() > 0
    t.discs(xyz[sp], 1.8, "#FFE9A8", 0.95, order="depth", label="spiking cells (M0)")
    out["spiking"] = t.resolve()
    t.save(OUT / "fig4a_spiking_glass.png", out["spiking"], dict(spiking_cells=int(sp.sum())))
    return out, t.view


CHIMERAX_SCRIPT = """# Generated by manuscript/figures/render/pilot.py; run by ChimeraX (session is provided).
from chimerax.core.commands import run
from chimerax.geometry import Place
run(session, "open {obj}")
run(session, "windowsize {w2} {h2}")
run(session, "set bgColor black")
run(session, "camera ortho")
cam = session.main_view.camera
cam.position = Place(origin=({cx:.4f}, {cy:.4f}, 5000.0))
cam.field_width = {field:.4f}
cam.redraw_needed = True
run(session, "color #6E7A86")
run(session, "material dull")
run(session, "lighting soft multiShadow 512")
run(session, "lighting intensity 0.9 ambientIntensity 1.4")
run(session, "graphics silhouettes true width 1.2 color #0A0C0E depthJump 0.01")
run(session, "camera")
run(session, "save {png} width {W} height {H} supersample 3 transparentBackground true")
"""


def export_unfolded_obj(regions, view, path):
    """Neuropil meshes in ChimeraX scene coordinates (x = X, y = -Y, z = -depth; um), one object per region."""
    lines, base = [], 1
    for meta, v, f in regions:
        if not no_lamina(meta):
            continue
        c, _ = view.camera(v, side=meta["dataset"] == "vnc")
        lines.append(f"o {meta['label']}")
        lines += [f"v {x:.3f} {-y:.3f} {-z:.3f}" for x, y, z in c]
        lines += [f"f {a + base} {b + base} {d + base}" for a, b, d in f]
        base += len(v)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def signed_chimerax(cells, view):
    from PIL import Image
    cx_dir = OUT / "chimerax"
    cx_dir.mkdir(parents=True, exist_ok=True)
    obj = cx_dir / "unfolded_shell.obj"
    export_unfolded_obj(rp.load_regions(), view, obj)
    W, H = view.width, view.height
    png = cx_dir / "shell_rgba.png"
    script = cx_dir / "shell_render.py"
    field = W * view.um_per_px
    script.write_text(CHIMERAX_SCRIPT.format(obj=obj.as_posix(), w2=W // 2, h2=H // 2, cx=view.centre[0], cy=-view.centre[1],
                                             field=field, png=png.as_posix(), W=W, H=H), encoding="utf-8", newline="\n")
    t = time.time()
    r = subprocess.run([str(CHIMERAX), "--nostatus", "--notools", "--script", str(script), "--exit"], capture_output=True,
                       text=True, timeout=900)
    (cx_dir / "chimerax.log").write_text(f"returncode {r.returncode}\n{r.stdout}\n{r.stderr}", encoding="utf-8", newline="\n")
    if not png.exists():
        raise RuntimeError(f"ChimeraX produced no image (see {cx_dir / 'chimerax.log'})")
    shell = np.asarray(Image.open(png).convert("RGBA"), np.float64) / 255
    if shell.shape[:2] != (H, W):
        raise RuntimeError(f"ChimeraX image is {shell.shape[:2]}, expected {(H, W)}")
    s, xyz = somata(cells)
    tile = rp.Tile(view)
    up = np.repeat(np.repeat(shell, view.ss, axis=0), view.ss, axis=1)
    tile.img[:] = rp.srgb_to_linear(up[..., :3]) * up[..., 3:4] * 0.32
    tile.log["layers"].append(dict(kind="chimerax_shell", seconds=round(time.time() - t, 1), script=script.name, field_width_um=field))
    background(tile, xyz)
    signed_layer(tile, s, xyz)
    rgb = tile.resolve()
    tile.save(OUT / "fig4a_signed_chimerax.png", rgb)
    return rgb


def arbor_segments(cells, arbors):
    pts, offs, cnts, body = arbors
    by_body = cells.set_index("body_id")
    cls = by_body.loc[body, "superclass"].map(pal.READOUT_CLASS).fillna("other").to_numpy()
    role = by_body.loc[body, "role"].to_numpy()
    idx = [i for i in np.flatnonzero(role == "readout") if cnts[i] > 0]
    cable = np.array([np.linalg.norm(pts[offs[i] + 1:offs[i] + cnts[i]:2] - pts[offs[i]:offs[i] + cnts[i]:2], axis=1).sum() for i in idx])
    n_class = pd.Series(cls[idx]).map(pd.Series(cls[idx]).value_counts()).to_numpy()
    # similar ink per neuron whatever its size, and similar ink per class whatever its size (the 2,109 central-brain cells
    # would otherwise wash the brain out)
    alpha = np.clip(0.16 * np.sqrt(np.median(cable) / cable) * np.sqrt(624 / n_class), 0.02, 0.30)
    a, b, col, al = [], [], [], []
    for k, i in enumerate(idx):
        p = pts[offs[i]:offs[i] + cnts[i]].astype(np.float64)
        m = len(p) // 2
        a.append(p[0::2])
        b.append(p[1::2])
        col.append(np.repeat(rp.hex_linear(pal.READOUT_ON_DARK[cls[i]])[None], m, axis=0))
        al.append(np.full(m, alpha[k]))
    return np.vstack(a), np.vstack(b), np.vstack(col), np.concatenate(al), len(idx)


def anchor(cells, segs, name):
    c, d = ANCHOR_VIEWS[name]
    s, xyz = somata(cells)
    view = rp.fit_view(xyz, px(ANCHOR_W), px(ANCHOR_H), R=rp.look(c, d), margin=0.035, ss=2)
    tile = rp.Tile(view)
    tile.shell(rp.load_regions(), colour=SHELL, strength=0.10, gamma=2.2, fill=0.012, select=no_lamina)
    background(tile, xyz, 0.28)
    a, b, col, al, n = segs
    tile.segments(a, b, 0.28, col, al, depth_cue=0.6, label=f"{n} readout arbors")
    inp = s[s["role"] == "input"][["soma_x_um", "soma_y_um", "soma_z_um"]].to_numpy()
    tile.discs(inp, 0.9, pal.TILE["input"], 0.6, order="depth", label="3,200 input somata")
    rgb = tile.resolve()
    tile.save(OUT / f"fig1a_anchor_{name}.png", rgb)
    return rgb


def sheet(trip, chim, anchors):
    """All tiles at their final print size on one page (taller than a figure; for choosing the look only)."""
    cv = fs.Canvas(fs.FULL, 7.0 + TILE_H + 2 * (ANCHOR_H + 6.0) + 2.0)
    cv.text(0, 1.0, "Renderer pilot, every tile at final print size (600 ppi). Row 1: Fig. 4a tiles. Rows 2-3: Fig. 1a anchor options.",
            size=fs.PT, va="top", fontweight="bold")
    y = 7.0
    labels = ["Signed cue difference, glass shell", "|Cue difference|, max projection", "Spiking cells", "Signed, ChimeraX shell"]
    for k, (lab, im) in enumerate(zip(labels, [trip["signed"], trip["magnitude"], trip["spiking"], chim])):
        x = k * (TILE_W + 2.0) + (6.0 if k == 3 else 0.0)
        cv.text(x, y - 1.0, lab, size=fs.PT_SMALL, va="bottom")
        cv.tile(x, y, im, width=TILE_W)
    y += TILE_H + 6.0
    for name, im in anchors.items():
        cv.text(0, y - 1.0, f"Fig. 1a anchor: {name.replace('_', ' ')}", size=fs.PT_SMALL, va="bottom")
        cv.tile(0, y, im, width=ANCHOR_W)
        y += ANCHOR_H + 6.0
    cv.save(OUT, "pilot_sheet", preview_dir=OUT, jpg=False)
    cv.close()


def main():
    t = time.time()
    OUT.mkdir(parents=True, exist_ok=True)
    cells = load_cells()
    trip, view = triptych(cells)
    print(f"Fig. 4a triptych {time.time() - t:.1f}s", flush=True)
    chim = signed_chimerax(cells, view)
    print(f"ChimeraX tile {time.time() - t:.1f}s", flush=True)
    segs = arbor_segments(cells, rp.load_arbors())
    anchors = {name: anchor(cells, segs, name) for name in ANCHOR_VIEWS}
    print(f"anchors {time.time() - t:.1f}s", flush=True)
    sheet(trip, chim, anchors)
    print(f"done {time.time() - t:.1f}s", flush=True)


if __name__ == "__main__":
    main()
