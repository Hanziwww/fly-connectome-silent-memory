r"""Writes manuscript/paper/generated/values.tex from manuscript/writing/number_ledger.csv: one \cellval{ID}{display} per
ledger row, so that the LaTeX text writes every result as \val{ID} and never types it by hand. The display strings are the
ledger's (build_ledger.py FORMATS); here they only become TeX (percent signs escaped, "10^k" as a superscript).

  .\MIGRATION\python\python.exe -B -X utf8 -I manuscript\writing\build_macros.py
"""
import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEDGER = HERE / "number_ledger.csv"
OUT = HERE.parents[0] / "paper" / "generated" / "values.tex"


def tex(display: str) -> str:
    s = display.replace("%", r"\%")
    s = re.sub(r"10\^([−-]?\d+)", r"10\\textsuperscript{\1}", s)
    return s.replace(" × ", " × ")                # thin spaces around the times sign


def main():
    rows = list(csv.DictReader(open(LEDGER, encoding="utf-8")))
    seen = set()
    lines = ["% Generated by manuscript/writing/build_macros.py from manuscript/writing/number_ledger.csv; do not edit."]
    for r in rows:
        if r["id"] in seen:
            raise SystemExit(f"duplicate ledger id {r['id']}")
        seen.add(r["id"])
        if not r.get("display"):
            raise SystemExit(f"ledger row {r['id']} has no display form (rebuild the ledger)")
        lines.append(f"\\cellval{{{r['id']}}}{{{tex(r['display'])}}}% {r['statement'][:90]}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} values -> {OUT.relative_to(HERE.parents[1])}")


if __name__ == "__main__":
    main()
